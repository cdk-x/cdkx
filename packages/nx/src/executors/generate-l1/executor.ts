import type { PromiseExecutor } from '@nx/devkit';
import {
  DeployMetadataGenerator,
  Json2jsiiAdapter,
  PropsSerializerGenerator,
  ResourceWrapperGenerator,
  SchemaNormalizer,
  SingleRootClassifier,
  UnionDetector,
  type UnionOverride,
} from '@cdk-x/generator-toolkit';
import type { JSONSchema4 } from 'json-schema';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';

import { NxProjectRoots } from '../../internal/nx-project-roots';
import { SchemaOutputNaming } from '../../internal/schema-output-naming';
import type {
  GenerateL1ExecutorSchema,
  GenerateL1SchemaEntry,
  GenerateL1UnionOverride,
} from './schema';

/**
 * Generates one Resource's combined `.generated.ts` file: the header,
 * `json2jsii`'s rendered types (interfaces/enums only — see
 * `Json2jsiiAdapter`'s class doc for why serialization is generated
 * separately), the `PropsSerializerGenerator`-generated static serializer
 * class, and the `Resource` subclass wrapping them all together.
 */
function generateResourceFileSource(
  normalizedSchema: JSONSchema4,
  entry: GenerateL1SchemaEntry,
  apiVersion: string,
): string {
  const classified = SingleRootClassifier.classify(normalizedSchema, {
    resourceType: entry.resourceType,
  });
  const [root] = classified.roots;
  if (!root) {
    throw new Error(
      `SingleRootClassifier produced no Resource root for "${entry.file}".`,
    );
  }

  const unionOverrides = UnionDetector.detectAndResolve(
    normalizedSchema,
    toUnionOverrides(entry.unionOverrides),
  );
  const serializerClassName = `${root.resourceType}Serializer`;

  const { propsTypeName, source: typesSource } = Json2jsiiAdapter.generate(
    normalizedSchema,
    root,
    { unionOverrides },
  );
  const serializerSource = PropsSerializerGenerator.generate(
    normalizedSchema,
    root,
    propsTypeName,
    { serializerClassName, unionOverrides },
  );
  const wrapperSource = ResourceWrapperGenerator.generate({
    resourceType: root.resourceType,
    apiVersion,
    propsTypeName,
    serializerClassName,
  });

  return [
    '// AUTO-GENERATED by @cdk-x/generator-toolkit — do not edit by hand.',
    "// Regenerate via the owning library's `generate-l1` Nx target.",
    '',
    "import { Resource } from '@cdk-x/core';",
    "import { Construct } from 'constructs';",
    '',
    typesSource.trimEnd(),
    '',
    serializerSource.trimEnd(),
    '',
    wrapperSource.trimEnd(),
    '',
  ].join('\n');
}

/**
 * Converts the executor schema's plain-data `unionOverrides` config (an
 * escape hatch, rarely needed — see `UnionDetector`, which auto-detects and
 * auto-resolves the common case with no config at all) into
 * `UnionDetector.detectAndResolve()`'s function-based `UnionOverride` shape:
 * every variant but the last needs a `discriminantProperty` (checked via
 * `in`); the last variant is the unconditional fallback.
 */
function toUnionOverrides(
  overrides: GenerateL1UnionOverride[] | undefined,
): readonly UnionOverride[] {
  return (overrides ?? []).map((override) => {
    const variants = override.variants;
    return {
      unionTypeName: override.unionTypeName,
      variants: variants.map((variant, index) => {
        const isLast = index === variants.length - 1;
        if (!isLast && !variant.discriminantProperty) {
          throw new Error(
            `Union override "${override.unionTypeName}": variant "${variant.typeName}" needs a discriminantProperty (only the last variant may omit one).`,
          );
        }
        return {
          definitionName: variant.definitionName,
          typeName: variant.typeName,
          isVariant: variant.discriminantProperty
            ? (x: string) => `'${variant.discriminantProperty}' in (${x})`
            : () => 'true',
        };
      }),
    };
  });
}

/**
 * Generates L1 `Resource` TypeScript source from every vendored JSON Schema
 * file declared in `schemas`, in-process via `@cdk-x/generator-toolkit` — a
 * TypeScript library this workspace owns, not an external CLI, so unlike
 * the `jsii-*` executors this never shells out through `ProcessRunner`.
 *
 * Only ever produces `Resource` subclasses — never nested `Component`
 * constructs (see the L1 codegen plan): everything below a Resource root is
 * a plain, deeply-nested TypeScript interface/enum generated by
 * `json2jsii`. `SingleRootClassifier` is the only classifier wired in
 * today (every vendored schema so far is a single-file, single-root
 * document); a future Kubernetes-style provider needing many roots per
 * document would plug in a different classifier here.
 */
const runExecutor: PromiseExecutor<GenerateL1ExecutorSchema> = async (
  options,
  context,
) => {
  const projectRoot = NxProjectRoots.resolve(context);
  const outputDir = path.join(
    projectRoot,
    options.outputDir ?? 'src/lib/generated',
  );

  try {
    mkdirSync(outputDir, { recursive: true });

    for (const entry of options.schemas) {
      const rawSchema = JSON.parse(
        readFileSync(path.join(projectRoot, entry.file), 'utf-8'),
      ) as JSONSchema4;
      const normalizedSchema = SchemaNormalizer.normalize(rawSchema);

      const baseName = SchemaOutputNaming.baseName(entry.file);
      writeFileSync(
        path.join(outputDir, `${baseName}.generated.ts`),
        generateResourceFileSource(normalizedSchema, entry, options.apiVersion),
      );
      writeFileSync(
        path.join(outputDir, `${baseName}.deploy.generated.ts`),
        DeployMetadataGenerator.generate({
          resourceType: entry.resourceType,
          apiVersion: options.apiVersion,
          mode: entry.mode,
        }),
      );
    }

    return { success: true };
  } catch (error) {
    return {
      success: false,
      message: error instanceof Error ? error.message : String(error),
    };
  }
};

export default runExecutor;
