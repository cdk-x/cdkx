/**
 * How a Resource is meant to be deployed: `"synth-only"` for a Resource
 * whose synthesized properties are turned into a file (e.g. a GitHub
 * Actions workflow YAML file, no live API call — its lifecycle stops at
 * synth), `"deploy"` for one that's created via a provider API call. Pure
 * metadata — never affects the generated class shape, only what a
 * not-yet-built deploy engine does with it afterwards.
 */
export type DeployMode = 'synth-only' | 'deploy';

/**
 * The minimal identity of a generated Resource needed to key its deploy
 * metadata — deliberately not the full generated-class shape, since deploy
 * mode is orthogonal to a Resource's properties.
 */
export interface ResourceDeployMetadata {
  readonly resourceType: string;
  readonly apiVersion: string;
  readonly mode: DeployMode;
}

/**
 * Generates the small, separate source file carrying a Resource's deploy
 * mode (`"synth-only"` vs `"deploy"`) as metadata — deliberately kept out
 * of the Resource's own generated class (see {@link ResourceWrapperGenerator}),
 * since deploy mode never affects the generated shape, only what a
 * not-yet-built deploy engine does with it afterwards.
 */
export class DeployMetadataGenerator {
  private constructor() {} // no instances — static-only class

  /**
   * Generates the deploy-metadata source file for one Resource.
   *
   * @param resource - the Resource whose deploy mode to emit.
   * @returns the generated TypeScript source, ending in a trailing newline.
   * @example
   * const source = DeployMetadataGenerator.generate(resource);
   */
  public static generate(resource: ResourceDeployMetadata): string {
    const key = `${resource.apiVersion}/${resource.resourceType}`;
    return [
      '// AUTO-GENERATED by @cdk-x/generator-toolkit — do not edit by hand.',
      "// Regenerate via the owning library's `generate-l1` Nx target.",
      '',
      'export interface DeployConfig {',
      "  readonly mode: 'synth-only' | 'deploy';",
      '}',
      '',
      'export const DEPLOY_CONFIGS: Record<string, DeployConfig> = {',
      `  '${key}': { mode: '${resource.mode}' },`,
      '};',
      '',
    ].join('\n');
  }
}
